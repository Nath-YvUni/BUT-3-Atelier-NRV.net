<?php
declare(strict_types=1);

use Dotenv\Dotenv;
use nrv\adapters\config\ContainerConfig;
use nrv\adapters\spi\repositories\PDOPanierRepository;

beforeEach(function () {
    $racineApp = dirname(__DIR__, 2);

    Dotenv::createImmutable($racineApp . '/config')->load();

    $this->pdo = ContainerConfig::build()->get('nrv.pdo');

    $this->pdo->beginTransaction();

    $this->pdo->exec(<<<'SQL'
        CREATE TEMP TABLE "soiree" (
            "id" integer PRIMARY KEY,
            "nom" varchar(100) NOT NULL,
            "date_heure_debut" timestamp NOT NULL
        ) ON COMMIT DROP;

        CREATE TEMP TABLE "tarif" (
            "id" integer PRIMARY KEY,
            "categorie" varchar(10) NOT NULL,
            "prix" numeric(6,2) NOT NULL
        ) ON COMMIT DROP;

        CREATE TEMP TABLE "panier" (
            "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "utilisateur_id" integer NOT NULL UNIQUE
        ) ON COMMIT DROP;

        CREATE TEMP TABLE "ligne_panier" (
            "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "panier_id" integer NOT NULL,
            "soiree_id" integer NOT NULL,
            "tarif_id" integer NOT NULL,
            "quantite" integer NOT NULL,
            UNIQUE ("panier_id", "soiree_id", "tarif_id")
        ) ON COMMIT DROP;

        CREATE TEMP TABLE "commande" (
            "id" integer PRIMARY KEY,
            "panier_id" integer UNIQUE,
            "statut" varchar(15) NOT NULL
        ) ON COMMIT DROP;

        CREATE TEMP TABLE "pass_trois_jours" (
            "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "panier_id" integer,
            "tarif_id" integer NOT NULL,
            "taux_remise" numeric(4,2) NOT NULL
        ) ON COMMIT DROP;

        CREATE TEMP TABLE "pass_soiree" (
            "pass_id" integer NOT NULL,
            "soiree_id" integer NOT NULL,
            PRIMARY KEY ("pass_id", "soiree_id")
        ) ON COMMIT DROP;

        INSERT INTO "soiree" ("id", "nom", "date_heure_debut") VALUES
            (2, 'Blues Night', '2027-06-05 20:30:00'),
            (3, 'Metal Storm', '2027-06-08 19:30:00'),
            (5, 'Reggae Vibration', '2027-06-12 20:00:00'),
            (6, 'Punk Attitude', '2027-06-15 20:30:00');

        INSERT INTO "tarif" ("id", "categorie", "prix") VALUES
            (1, 'normal', 35.00),
            (2, 'reduit', 25.50);
        SQL);

    $this->repository = new PDOPanierRepository($this->pdo);
});

afterEach(function () {
    $pdo = $this->pdo ?? null;

    if ($pdo instanceof PDO && $pdo->inTransaction()) {
        $pdo->rollBack();
    }
});

test('retourne null quand l\'utilisateur n\'a pas de panier', function () {
    expect($this->repository->trouverParUtilisateur(3))->toBeNull();
});

test('crée le panier et la ligne au premier ajout', function () {
    $this->repository->ajouterBillets(3, 2, 1, 2);

    $panier = $this->repository->trouverParUtilisateur(3);

    expect($panier->getLignes())->toHaveCount(1);

    $ligne = $panier->getLignes()[0];

    expect($ligne->getSoiree()->getNom())->toBe('Blues Night');
    expect($ligne->getSoiree()->getDateHeureDebut()->format('Y-m-d H:i'))->toBe('2027-06-05 20:30');
    expect($ligne->getTarif()->getCategorie())->toBe('normal');
    expect($ligne->getTarif()->getPrix())->toBe(3500);
    expect($ligne->getQuantite())->toBe(2);
    expect($panier->estModifiable())->toBeTrue();
});

test('additionne la quantité sur une ligne soirée/tarif existante', function () {
    $this->repository->ajouterBillets(3, 2, 1, 2);
    $this->repository->ajouterBillets(3, 2, 1, 3);

    $lignes = $this->repository->trouverParUtilisateur(3)->getLignes();

    expect($lignes)->toHaveCount(1);
    expect($lignes[0]->getQuantite())->toBe(5);
});

test('crée une ligne distincte pour un autre tarif ou une autre soirée', function () {
    $this->repository->ajouterBillets(3, 2, 1, 1);
    $this->repository->ajouterBillets(3, 2, 2, 1);
    $this->repository->ajouterBillets(3, 5, 1, 1);

    $panier = $this->repository->trouverParUtilisateur(3);

    expect($panier->getLignes())->toHaveCount(3);
    expect($panier->montantTotal())->toBe(3500 + 2550 + 3500);
});

test('ne mélange pas les paniers de deux utilisateurs', function () {
    $this->repository->ajouterBillets(3, 2, 1, 2);
    $this->repository->ajouterBillets(4, 5, 2, 1);

    $lignes = $this->repository->trouverParUtilisateur(3)->getLignes();

    expect($lignes)->toHaveCount(1);
    expect($lignes[0]->getSoiree()->getId())->toBe(2);
});

test('charge les pass du panier avec leurs soirées', function () {
    $this->repository->ajouterBillets(3, 2, 1, 1);

    $this->pdo->exec(<<<'SQL'
        INSERT INTO "pass_trois_jours" ("id", "panier_id", "tarif_id", "taux_remise")
        SELECT 7, "id", 1, 3.00 FROM "panier" WHERE "utilisateur_id" = 3;

        INSERT INTO "pass_soiree" ("pass_id", "soiree_id") VALUES (7, 6), (7, 3), (7, 5);
        SQL);

    $pass = $this->repository->trouverParUtilisateur(3)->getPass();

    expect($pass)->toHaveCount(1);
    expect($pass[0]->getTauxRemise())->toBe(300);

    $soirees = array_map(fn($soiree) => $soiree->getId(), $pass[0]->getSoirees());

    expect($soirees)->toBe([3, 5, 6]);
});

test('indique la commande en attente qui verrouille le panier', function () {
    $this->repository->ajouterBillets(3, 2, 1, 1);

    $this->pdo->exec(<<<'SQL'
        INSERT INTO "commande" ("id", "panier_id", "statut")
        SELECT 9, "id", 'en_attente' FROM "panier" WHERE "utilisateur_id" = 3;
        SQL);

    $panier = $this->repository->trouverParUtilisateur(3);

    expect($panier->getCommandeEnAttenteId())->toBe(9);
    expect($panier->estModifiable())->toBeFalse();
});

test('crée le panier et le pass avec ses trois soirées', function () {
    $this->repository->ajouterPass(3, 1, [6, 3, 5], 300);

    $panier = $this->repository->trouverParUtilisateur(3);

    expect($panier->getLignes())->toBe([]);
    expect($panier->getPass())->toHaveCount(1);

    $pass = $panier->getPass()[0];

    expect($pass->getTarif()->getPrix())->toBe(3500);
    expect($pass->getTauxRemise())->toBe(300);
    expect(array_map(fn($soiree) => $soiree->getId(), $pass->getSoirees()))->toBe([3, 5, 6]);
    expect($panier->montantTotal())->toBe(10185);
});

test('ajoute un second pass à côté des billets existants', function () {
    $this->repository->ajouterBillets(3, 2, 1, 2);
    $this->repository->ajouterPass(3, 2, [3, 5, 6], 300);
    $this->repository->ajouterPass(3, 1, [2, 3, 5], 300);

    $panier = $this->repository->trouverParUtilisateur(3);

    expect($panier->getLignes())->toHaveCount(1);
    expect($panier->getPass())->toHaveCount(2);
    expect($panier->nombreBillets())->toBe(8);
});
