const TABLES_TEMPORAIRES_COMMANDE = [
    'billet',
    'pass_soiree',
    'pass_trois_jours',
    'commande',
    'ligne_panier',
    'panier',
    'tarif',
    'soiree'
];

function panierPaiementTest(): Panier
{
    return new Panier(
        1,
        [
            new LignePanier(
                1,
                new SoireeResume(
                    2,
                    'Blues Night',
                    new DateTimeImmutable('2027-06-05 20:30:00')
                ),
                new Tarif(1, 'normal', 3500),
                2
            ),
            new LignePanier(
                2,
                new SoireeResume(
                    5,
                    'Reggae Vibration',
                    new DateTimeImmutable('2027-06-12 20:00:00')
                ),
                new Tarif(2, 'reduit', 2500),
                1
            ),
        ],
        [
            new PassTroisJours(
                2,
                new Tarif(2, 'reduit', 2500),
                300,
                [
                    new SoireeResume(3, 'Metal Storm', new DateTimeImmutable('2027-06-08 19:30:00')),
                    new SoireeResume(5, 'Reggae Vibration', new DateTimeImmutable('2027-06-12 20:00:00')),
                    new SoireeResume(6, 'Punk Attitude', new DateTimeImmutable('2027-06-15 20:30:00')),
                ]
            ),
        ],
        null
    );
}

beforeEach(function () {
    $racineApp = dirname(__DIR__, 2);

    Dotenv::createImmutable($racineApp . '/config')->load();

    $this->pdo = ContainerConfig::build()->get('nrv.pdo');

    $this->pdo->exec(<<<'SQL'
        CREATE TEMP TABLE "tarif" (
            "id" integer PRIMARY KEY,
            "categorie" varchar(10) NOT NULL,
            "prix" numeric(6,2) NOT NULL
        );

        CREATE TEMP TABLE "panier" (
            "id" integer PRIMARY KEY,
            "utilisateur_id" integer NOT NULL UNIQUE
        );

        CREATE TEMP TABLE "ligne_panier" (
            "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "panier_id" integer NOT NULL,
            "soiree_id" integer NOT NULL,
            "tarif_id" integer NOT NULL,
            "quantite" integer NOT NULL
        );

        CREATE TEMP TABLE "commande" (
            "id" integer GENERATED BY DEFAULT AS IDENTITY (START WITH 10) PRIMARY KEY,
            "utilisateur_id" integer NOT NULL,
            "panier_id" integer UNIQUE REFERENCES "panier"("id") ON DELETE SET NULL,
            "reference" varchar(30) NOT NULL UNIQUE,
            "date_commande" timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
            "statut" varchar(15) NOT NULL DEFAULT 'en_attente',
            "montant_total" numeric(8,2) NOT NULL
        );

        CREATE TEMP TABLE "pass_trois_jours" (
            "id" integer PRIMARY KEY,
            "panier_id" integer,
            "commande_id" integer,
            "tarif_id" integer NOT NULL,
            "taux_remise" numeric(4,2) NOT NULL
        );

        CREATE TEMP TABLE "pass_soiree" (
            "pass_id" integer NOT NULL,
            "soiree_id" integer NOT NULL
        );

        CREATE TEMP TABLE "soiree" (
            "id" integer PRIMARY KEY,
            "nom" varchar(100) NOT NULL,
            "capacite" integer NOT NULL
        );

        CREATE TEMP TABLE "billet" (
            "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "commande_id" integer NOT NULL,
            "soiree_id" integer NOT NULL,
            "tarif_id" integer NOT NULL,
            "pass_id" integer,
            "reference" varchar(30) NOT NULL,
            "token" varchar(64) NOT NULL,
            "prix" numeric(8,2) NOT NULL
        );

        INSERT INTO "tarif" ("id", "categorie", "prix") VALUES
            (1, 'normal', 35.00),
            (2, 'reduit', 25.00);

        INSERT INTO "panier" ("id", "utilisateur_id") VALUES
            (1, 3),
            (2, 5);

        INSERT INTO "ligne_panier" ("panier_id", "soiree_id", "tarif_id", "quantite") VALUES
            (1, 2, 1, 2),
            (1, 5, 2, 1);

        INSERT INTO "pass_trois_jours"
            ("id", "panier_id", "tarif_id", "taux_remise")
        VALUES
            (2, 1, 2, 3.00);

        INSERT INTO "pass_soiree" ("pass_id", "soiree_id") VALUES
            (2, 3),
            (2, 5),
            (2, 6);

        INSERT INTO "soiree" ("id", "nom", "capacite") VALUES
            (2, 'Blues Night', 100),
            (3, 'Metal Storm', 100),
            (5, 'Reggae Vibration', 100),
            (6, 'Punk Attitude', 100);
        SQL);

    $this->repository = new PDOCommandeRepository($this->pdo);
});

afterEach(function () {
    $pdo = $this->pdo ?? null;

    if ($pdo instanceof PDO) {
        $pdo->exec(
            'DROP TABLE IF EXISTS pg_temp.' .
            implode(', pg_temp.', TABLES_TEMPORAIRES_COMMANDE)
        );
    }
});

test('crée une commande en attente avec le montant du panier', function () {
    expect($this->repository->commander(3, []))->toBeTrue();

    $commandes = $this->repository->findByUser(3);

    expect($commandes)->toHaveCount(1);
    expect($commandes[0]->getPanierId())->toBe(1);
    expect($commandes[0]->getStatut())->toBe('en_attente');
    expect($commandes[0]->getMontantTotal())->toBe(7000 + 2500 + 7275);
    expect($commandes[0]->getReference())->toStartWith('CMD-');
});

test('ne crée pas de deuxième commande tant que la première est en attente', function () {
    $this->repository->commander(3, []);

    expect($this->repository->commander(3, []))->toBeFalse();
    expect($this->repository->findByUser(3))->toHaveCount(1);
});

test('crée une nouvelle commande quand la précédente a été refusée', function () {
    $this->repository->commander(3, []);

    $this->pdo->exec(
        "UPDATE \"commande\" SET \"statut\" = 'refusee'"
    );

    expect($this->repository->commander(3, []))->toBeTrue();

    $commandes = $this->repository->findByUser(3);

    expect($commandes)->toHaveCount(2);
    expect(array_map(
        fn($commande) => $commande->getPanierId(),
        $commandes
    ))->toContain(null, 1);
});

test('refuse la commande d un panier vide ou absent', function (int $utilisateurId) {
    expect(fn() => $this->repository->commander($utilisateurId, []))
        ->toThrow(PanierVideException::class);

    expect($this->repository->findByUser($utilisateurId))->toBe([]);
})->with([
            'panier sans contenu' => 5,
            'pas de panier' => 9,
        ]);

test('ne retourne une commande qu à son propriétaire', function () {
    $this->repository->commander(3, []);
    $id = $this->repository->findByUser(3)[0]->getId();

    expect($this->repository->findById(3, $id)?->getId())->toBe($id);
    expect($this->repository->findById(4, $id))->toBeNull();
});

test('paie une commande lorsque les places sont suffisantes', function () {
    $this->repository->commander(3, []);

    $commandeId = $this->repository->findByUser(3)[0]->getId();
    $panier = panierPaiementTest();
    $generationAppelee = false;

    $genererBillets = function (int $id, Panier $panierRecu) use (&$generationAppelee) {
        $generationAppelee = true;

        expect($panierRecu->nombreBillets())->toBe(6);

        $numero = 1;

        foreach ($panierRecu->getLignes() as $ligne) {
            for ($i = 0; $i < $ligne->getQuantite(); $i++) {
                $requete = $this->pdo->prepare(
                    'INSERT INTO "billet"
                    ("commande_id", "soiree_id", "tarif_id", "pass_id", "reference", "token", "prix")
                    VALUES (?, ?, ?, ?, ?, ?, ?)'
                );

                $requete->execute([
                    $id,
                    $ligne->getSoiree()->getId(),
                    $ligne->getTarif()->getId(),
                    null,
                    'BIL-TEST-' . $numero,
                    bin2hex(random_bytes(32)),
                    $ligne->getTarif()->getPrix() / 100
                ]);

                $numero++;
            }
        }

        foreach ($panierRecu->getPass() as $pass) {
            foreach ($pass->getSoirees() as $rang => $soiree) {
                $prix = $pass->prixBillets()[$rang];

                $requete = $this->pdo->prepare(
                    'INSERT INTO "billet"
                    ("commande_id", "soiree_id", "tarif_id", "pass_id", "reference", "token", "prix")
                    VALUES (?, ?, ?, ?, ?, ?, ?)'
                );

                $requete->execute([
                    $id,
                    $soiree->getId(),
                    $pass->getTarif()->getId(),
                    $pass->getId(),
                    'BIL-TEST-' . $numero,
                    bin2hex(random_bytes(32)),
                    $prix / 100
                ]);

                $numero++;
            }
        }
    };

    $manques = $this->repository->payer(
        $commandeId,
        $panier,
        $genererBillets
    );

    expect($manques)->toBe([]);
    expect($generationAppelee)->toBeTrue();

    $commande = $this->repository->findById(3, $commandeId);

    expect($commande->getStatut())->toBe('payee');
    expect($commande->getPanierId())->toBeNull();

    $nombreBillets = $this->pdo->query(
        'SELECT COUNT(*) FROM "billet"'
    )->fetchColumn();

    expect((int) $nombreBillets)->toBe(6);

    $panierRestant = $this->pdo->query(
        'SELECT COUNT(*) FROM "panier" WHERE "id" = 1'
    )->fetchColumn();

    expect((int) $panierRestant)->toBe(0);

    $passCommande = $this->pdo->query(
        'SELECT "commande_id" FROM "pass_trois_jours" WHERE "id" = 2'
    )->fetchColumn();

    expect((int) $passCommande)->toBe($commandeId);
});

test('refuse le paiement lorsque les places sont insuffisantes', function () {
    $this->repository->commander(3, []);

    $commandeId = $this->repository->findByUser(3)[0]->getId();

    $this->pdo->exec(
        'UPDATE "soiree" SET "capacite" = 1 WHERE "id" = 2'
    );

    $generationAppelee = false;

    $genererBillets = function () use (&$generationAppelee) {
        $generationAppelee = true;
    };

    $manques = $this->repository->payer(
        $commandeId,
        panierPaiementTest(),
        $genererBillets
    );

    expect($manques)->not->toBe([]);
    expect($generationAppelee)->toBeFalse();

    $nombreBillets = $this->pdo->query(
        'SELECT COUNT(*) FROM "billet"'
    )->fetchColumn();

    expect((int) $nombreBillets)->toBe(0);

    $commande = $this->repository->findById(3, $commandeId);

    expect($commande->getStatut())->toBe('refusee');
});

test('ne crée aucun billet si la commande est déjà payée', function () {
    $this->repository->commander(3, []);

    $commandeId = $this->repository->findByUser(3)[0]->getId();

    $requete = $this->pdo->prepare(
        'UPDATE "commande" SET "statut" = :statut WHERE "id" = :id'
    );

    $requete->execute([
        'statut' => 'payee',
        'id' => $commandeId
    ]);

    $generationAppelee = false;

    $genererBillets = function () use (&$generationAppelee) {
        $generationAppelee = true;
    };

    $this->repository->payer(
        $commandeId,
        panierPaiementTest(),
        $genererBillets
    );

    expect($generationAppelee)->toBeFalse();

    $nombreBillets = $this->pdo->query(
        'SELECT COUNT(*) FROM "billet"'
    )->fetchColumn();

    expect((int) $nombreBillets)->toBe(0);
});
