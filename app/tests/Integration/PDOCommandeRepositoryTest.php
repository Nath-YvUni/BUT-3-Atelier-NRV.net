<?php
declare(strict_types=1);

use Dotenv\Dotenv;
use nrv\adapters\config\ContainerConfig;
use nrv\adapters\spi\repositories\PDOCommandeRepository;
use nrv\application\exceptions\PanierVideException;

const TABLES_TEMPORAIRES_COMMANDE = ['tarif', 'panier', 'ligne_panier', 'commande', 'pass_trois_jours', 'pass_soiree'];

beforeEach(function () {
    $racineApp = dirname(__DIR__, 2);

    Dotenv::createImmutable($racineApp . '/config')->load();

    $this->pdo = ContainerConfig::build()->get('nrv.pdo');

    $this->pdo->exec(<<<'SQL'
        CREATE TEMP TABLE "tarif" (
            "id" integer PRIMARY KEY,
            "categorie" varchar(10) NOT NULL,
            "prix" numeric(6,2) NOT NULL
        );

        CREATE TEMP TABLE "panier" (
            "id" integer PRIMARY KEY,
            "utilisateur_id" integer NOT NULL UNIQUE
        );

        CREATE TEMP TABLE "ligne_panier" (
            "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "panier_id" integer NOT NULL,
            "soiree_id" integer NOT NULL,
            "tarif_id" integer NOT NULL,
            "quantite" integer NOT NULL
        );

        CREATE TEMP TABLE "commande" (
            "id" integer GENERATED BY DEFAULT AS IDENTITY (START WITH 10) PRIMARY KEY,
            "utilisateur_id" integer NOT NULL,
            "panier_id" integer UNIQUE,
            "reference" varchar(30) NOT NULL UNIQUE,
            "date_commande" timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
            "statut" varchar(15) NOT NULL DEFAULT 'en_attente',
            "montant_total" numeric(8,2) NOT NULL
        );

        CREATE TEMP TABLE "pass_trois_jours" (
            "id" integer PRIMARY KEY,
            "panier_id" integer,
            "tarif_id" integer NOT NULL,
            "taux_remise" numeric(4,2) NOT NULL
        );

        CREATE TEMP TABLE "pass_soiree" (
            "pass_id" integer NOT NULL,
            "soiree_id" integer NOT NULL
        );

        INSERT INTO "tarif" ("id", "categorie", "prix") VALUES
            (1, 'normal', 35.00),
            (2, 'reduit', 25.00);

        INSERT INTO "panier" ("id", "utilisateur_id") VALUES
            (1, 3),
            (2, 5);

        INSERT INTO "ligne_panier" ("panier_id", "soiree_id", "tarif_id", "quantite") VALUES
            (1, 2, 1, 2),
            (1, 5, 2, 1);

        INSERT INTO "pass_trois_jours" ("id", "panier_id", "tarif_id", "taux_remise") VALUES
            (2, 1, 2, 3.00);

        INSERT INTO "pass_soiree" ("pass_id", "soiree_id") VALUES
            (2, 3), (2, 5), (2, 6);
        SQL);

    $this->repository = new PDOCommandeRepository($this->pdo);
});

afterEach(function () {
    $pdo = $this->pdo ?? null;

    if ($pdo instanceof PDO) {
        $pdo->exec('DROP TABLE IF EXISTS pg_temp.' . implode(', pg_temp.', TABLES_TEMPORAIRES_COMMANDE));
    }
});

test('crée une commande en attente avec le montant du panier', function () {
    expect($this->repository->commander(3, []))->toBeTrue();

    $commandes = $this->repository->findByUser(3);

    expect($commandes)->toHaveCount(1);
    expect($commandes[0]->getPanierId())->toBe(1);
    expect($commandes[0]->getStatut())->toBe('en_attente');
    expect($commandes[0]->getMontantTotal())->toBe(7000 + 2500 + 7275);
    expect($commandes[0]->getReference())->toStartWith('CMD-');
});

test('ne crée pas de deuxième commande tant que la première est en attente', function () {
    $this->repository->commander(3, []);

    expect($this->repository->commander(3, []))->toBeFalse();
    expect($this->repository->findByUser(3))->toHaveCount(1);
});

test('crée une nouvelle commande quand la précédente a été refusée', function () {
    $this->repository->commander(3, []);
    $this->pdo->exec('UPDATE "commande" SET "statut" = \'refusee\'');

    expect($this->repository->commander(3, []))->toBeTrue();

    $commandes = $this->repository->findByUser(3);

    expect($commandes)->toHaveCount(2);
    expect(array_map(fn($commande) => $commande->getPanierId(), $commandes))->toContain(null, 1);
});

test('refuse la commande d\'un panier vide ou absent', function (int $utilisateurId) {
    expect(fn() => $this->repository->commander($utilisateurId, []))
        ->toThrow(PanierVideException::class);

    expect($this->repository->findByUser($utilisateurId))->toBe([]);
})->with([
    'panier sans contenu' => 5,
    'pas de panier' => 9,
]);

test('ne retourne une commande qu\'à son propriétaire', function () {
    $this->repository->commander(3, []);
    $id = $this->repository->findByUser(3)[0]->getId();

    expect($this->repository->findById(3, $id)?->getId())->toBe($id);
    expect($this->repository->findById(4, $id))->toBeNull();
});
